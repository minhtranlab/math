#!/usr/bin/env python3
"""Skill map JSON(s) (project folder skillmap/<topic>.json) -> src/Skills.gs (GENERATED, public: IDs + names + prerequisites only).

    python3 tools/build_skills.py "<project folder>/skillmap/trigonometry.json" [more.json ...]

Only these fields go into the repo: topic, skill, sub-skill IDs and short names, suggested prerequisites. Never examples,
sources, question counts or anything from private files. The Sheet's Skills tab is re-seeded from Skills.gs on every deploy
(Library.gs syncSkills_, safe to re-run: Minh's active/note kept; a sub-skill that left the map stays as active = No).
"""
import json, sys, os, re

TOPIC_NAMES = {'PYTH': 'Pythagoras', 'TRIG': 'Trigonometry'}
ID = re.compile(r'^[A-Z0-9]+(\.[A-Z0-9_]+){1,2}$')


def main(paths):
    rows, versions = [], []
    for p in paths:
        d = json.load(open(p, encoding='utf-8'))
        topic_main = d['topic']
        TOPIC_NAMES.setdefault(topic_main, d.get('name', topic_main))
        ver = str(d.get('status', '')).split(' ')[0] or d.get('schema', '')
        versions.append(f"{topic_main} {ver} ({d.get('date', '')})")
        for s in d['skills']:
            for u in s['subskills']:
                for x in (s['id'], u['id']):
                    if not ID.match(x):
                        sys.exit(f'bad ID {x}')
                rows.append({'topic': s['topic'], 'topic_name': TOPIC_NAMES.get(s['topic'], s['topic']), 'skill': s['id'], 'skill_name': s['name'],
                             'subskill': u['id'], 'subskill_name': u['name'], 'prereq': [x for x in u.get('prereq', []) if ID.match(x)]})
    ids = [r['subskill'] for r in rows]
    if len(ids) != len(set(ids)):
        sys.exit('duplicate sub-skill IDs')
    out = {'version': '; '.join(versions), 'rows': rows}
    dst = os.path.join(os.path.dirname(__file__), '..', 'src', 'Skills.gs')
    with open(dst, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by tools/build_skills.py from the project skill map(s) — do not edit by hand. IDs + names + prerequisites only.\n')
        f.write('var SKILLMAP_ = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'Skills.gs: {len(rows)} sub-skills in {len(set(r["skill"] for r in rows))} skills · {out["version"]}')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
